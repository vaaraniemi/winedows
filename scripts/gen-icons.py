#!/usr/bin/env python3
"""Generate the Winedows icon theme (desktop icons in the logo's style).

Every icon is the Edgy tile shape (a square with cut corners, top shine) in the
logo palette (wine red or blue) with a flat white glyph. Output goes to
build/config/includes.chroot/usr/share/icons/Winedows. Re-run after editing; do
not hand-edit the generated SVGs.
"""
import os

